#!/usr/bin/env python3
"""Render a TTF into an LVGL 8 bitmap font (.c), 4 bpp, printable ASCII.

usage: make_font.py FONT.ttf NAME SIZE [WEIGHT] > NAME.c
No kerning; good enough for UI labels. (Replaces lv_font_conv, which needs Node.)
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, name, size = sys.argv[1], sys.argv[2], int(sys.argv[3])
weight = int(sys.argv[4]) if len(sys.argv) > 4 else None

font = ImageFont.truetype(ttf, size)
if weight is not None:
    font.set_variation_by_axes([weight])
ascent, descent = font.getmetrics()

FIRST, LAST = 0x20, 0x7E
bitmap = bytearray()
glyphs = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 reserved */"]

for cp in range(FIRST, LAST + 1):
    ch = chr(cp)
    adv = font.getlength(ch)
    l, t, r, b = font.getbbox(ch, anchor="ls")  # relative to the baseline, y down
    w, h = max(0, r - l), max(0, b - t)
    start = len(bitmap)
    if w and h:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        px = img.tobytes()
        # 4 bpp, rows packed back to back (no per-row padding), glyph starts on a byte
        nib = [p >> 4 for p in px]
        if len(nib) % 2:
            nib.append(0)
        bitmap += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    glyphs.append(
        f"    {{.bitmap_index = {start}, .adv_w = {round(adv * 16)}, .box_w = {w}, .box_h = {h}, "
        f".ofs_x = {l}, .ofs_y = {-b}}} /* {ch!r} */")

out = sys.stdout
out.write(f"""/* {name}: generated by tools/make_font.py from {ttf.split('/')[-1]} at {size}px. Font licence: SIL OFL 1.1. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
""")
for i in range(0, len(bitmap), 24):
    out.write("    " + ", ".join(f"0x{x:02x}" for x in bitmap[i:i + 24]) + ",\n")
out.write(f"""}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(','+chr(10)).join(glyphs)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = {FIRST}, .range_length = {LAST - FIRST + 1}, .glyph_id_start = 1,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}
}};

static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
    .cache = &cache
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2,
    .underline_thickness = 1,
    .dsc = &font_dsc
}};
""")
